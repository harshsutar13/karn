"""
tools/approval_note.py

Multi-step agent: RAG retrieval → LLM draft → write .docx.
"""

from __future__ import annotations

import logging
import os
from dataclasses import dataclass

from rag.pipeline import rag_query
from models.llm import generate_response
from tools.docx_writer import write_docx

logger = logging.getLogger(__name__)

OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "..", "outputs")


@dataclass
class ApprovalNoteResult:
    output_path: str
    case_id: str
    draft_text: str
    sources: list[str]
    steps: list[str]


_DRAFT_SYSTEM = """\
You are drafting a MAINTENANCE APPROVAL NOTE for an industrial workbench.
Produce a real deliverable, structured EXACTLY as:

1. BACKGROUND
2. KEY FINDINGS
3. TECHNICAL EVALUATION
4. RCA STATUS
5. APPROVAL REQUESTED

Rules:
- Base every statement on the provided CONTEXT.
- Preserve numbers, units, and equipment tags verbatim.
- Do NOT invent cost, vendor, shutdown duration, or approval authority.
- If a field is unavailable in the context, write "(not available in prototype knowledge base)".
- Return ONLY the five numbered sections, no preamble.
"""


def _parse_sections(draft: str) -> list[dict]:
    """Split the LLM draft into {heading, body} sections."""
    sections: list[dict] = []
    current_heading = ""
    current_body: list[str] = []

    for raw_line in draft.splitlines():
        stripped = raw_line.strip()
        if not stripped:
            if current_body and current_body[-1] != "":
                current_body.append("")
            continue

        is_section = False
        for marker in ("1.", "2.", "3.", "4.", "5."):
            if stripped.upper().startswith(marker):
                is_section = True
                break

        if is_section:
            if current_heading or current_body:
                sections.append({
                    "heading": current_heading,
                    "body": "\n".join(current_body).strip(),
                })
            current_heading = stripped
            current_body = []
        else:
            current_body.append(stripped)

    if current_heading or current_body:
        sections.append({
            "heading": current_heading,
            "body": "\n".join(current_body).strip(),
        })

    return [s for s in sections if s["heading"] or s["body"]]


def generate_approval_note(
    case_id: str,
    equipment_tag: str = "P-101",
    additional_context: str = "",
) -> ApprovalNoteResult:
    """End-to-end: retrieve → draft → write .docx."""
    steps: list[str] = []

    # Step 1: retrieve
    query = (
        f"Current findings, historical baseline, and approval requirements "
        f"for {equipment_tag} {case_id}. {additional_context}"
    ).strip()

    rag = rag_query(query, top_k=5)
    steps.append(f"RAG retrieval: {rag.chunks_retrieved} chunks")
    logger.info("Approval note RAG retrieved %d chunks", rag.chunks_retrieved)

    context_block = "\n\n".join(
        f"[{s.filename}]\n{s.text_preview}" for s in rag.sources
    )

    # Step 2: draft
    prompt = (
        f"{_DRAFT_SYSTEM}\n\n"
        f"CASE ID: {case_id}\n"
        f"EQUIPMENT: {equipment_tag}\n\n"
        f"CONTEXT:\n{context_block}\n\n"
        f"DRAFT THE NOTE:"
    )

    draft = generate_response(prompt, think=False)
    steps.append("LLM draft generated")
    logger.info("Approval note draft length: %d chars", len(draft))

    # Step 3: parse
    sections = _parse_sections(draft)
    if not sections:
        sections = [{"heading": "Draft", "body": draft}]
    steps.append(f"Parsed {len(sections)} sections")

    # Step 4: write
    filename = f"{case_id}_approval_note.docx"
    output_path = os.path.join(OUTPUT_DIR, filename)

    unique_sources = list(dict.fromkeys(s.filename for s in rag.sources))

    written = write_docx(
        title=f"Maintenance Approval Note — {equipment_tag}",
        metadata={
            "Case ID": case_id,
            "Equipment": f"{equipment_tag} Centrifugal Pump",
            "Status": "PENDING HUMAN REVIEW",
            "Generated by": "SIH26 Sovereign AI Workbench",
        },
        sections=sections,
        sources=unique_sources,
        footer_note="SYNTHETIC PROTOTYPE — Human review mandatory before operational use.",
        output_path=output_path,
    )
    steps.append(f"Saved {os.path.basename(written)}")

    return ApprovalNoteResult(
        output_path=written,
        case_id=case_id,
        draft_text=draft,
        sources=unique_sources,
        steps=steps,
    )