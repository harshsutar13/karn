"""
api/rag.py

FastAPI router for RAG endpoints.

Endpoints:
    POST /api/rag/query          — Ask a question grounded in indexed documents
    POST /api/documents/ingest   — Ingest a document into the vector store
    GET  /api/rag/collection     — Collection info (points count, status, etc.)

Separation of concerns:
    This file only defines request/response schemas and route handlers.
    All business logic lives in rag/pipeline.py, rag/ingestion.py, rag/vector_store.py.
"""

import os
import sys
import logging

from fastapi import APIRouter, HTTPException, UploadFile, File, Form
from pydantic import BaseModel, Field

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from rag.pipeline import rag_query, RAGResponse
from rag.ingestion import ingest_document, IngestionResult
from rag.vector_store import get_client, collection_exists, get_collection_info
from config import QDRANT_COLLECTION


logger = logging.getLogger(__name__)

router = APIRouter()


# ---------------------------------------------------------------------------
# Request / Response schemas
# ---------------------------------------------------------------------------

class RAGQueryRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Natural-language question to answer")
    top_k: int = Field(default=5, ge=1, le=20, description="Max chunks to retrieve")
    score_threshold: float | None = Field(
        default=None, ge=0.0, le=1.0,
        description="Minimum cosine similarity. None = no filter."
    )
    collection: str = Field(
        default=QDRANT_COLLECTION,
        description="Qdrant collection to query"
    )


class SourceInfo(BaseModel):
    filename: str
    document_id: str
    chunk_index: int
    score: float
    char_start: int
    char_end: int
    text_preview: str


class RAGQueryResponse(BaseModel):
    answer: str
    sources: list[SourceInfo]
    query: str
    chunks_retrieved: int
    context_used: bool


class IngestResponse(BaseModel):
    filename: str
    document_id: str
    doc_type: str
    total_chars: int
    chunks_created: int
    chunks_upserted: int
    elapsed_total_s: float
    collection: str


class CollectionInfoResponse(BaseModel):
    name: str
    status: str
    points_count: int
    vector_size: int
    distance: str


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------

@router.post("/api/rag/query", response_model=RAGQueryResponse, tags=["RAG"])
def rag_query_endpoint(request: RAGQueryRequest):
    """
    Ask a natural-language question grounded in the indexed document collection.

    The answer is generated by the local LLM (Gemma 4 12B) using only the
    retrieved document context. If no relevant context is found, the model
    explicitly states that the documents do not contain sufficient information.

    Returns a structured response with the answer and source citations.
    """
    try:
        result: RAGResponse = rag_query(
            question=request.question,
            top_k=request.top_k,
            collection_name=request.collection,
            score_threshold=request.score_threshold,
        )
    except ConnectionError as exc:
        logger.error("Qdrant/Ollama not reachable: %s", exc)
        raise HTTPException(
            status_code=503,
            detail=f"AI services unavailable: {exc}"
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc))
    except Exception as exc:
        logger.exception("Unexpected error in rag_query_endpoint")
        raise HTTPException(status_code=500, detail=f"Internal error: {exc}")

    return RAGQueryResponse(
        answer=result.answer,
        sources=[
            SourceInfo(
                filename=s.filename,
                document_id=s.document_id,
                chunk_index=s.chunk_index,
                score=s.score,
                char_start=s.char_start,
                char_end=s.char_end,
                text_preview=s.text_preview,
            )
            for s in result.sources
        ],
        query=result.query,
        chunks_retrieved=result.chunks_retrieved,
        context_used=result.context_used,
    )


@router.post("/api/documents/ingest", response_model=IngestResponse, tags=["Documents"])
async def ingest_document_endpoint(
    file: UploadFile = File(..., description="Document to ingest (.pdf, .docx, .txt)"),
    collection: str = Form(default=QDRANT_COLLECTION, description="Target collection name"),
    department: str = Form(default=None, description="Optional department label"),
    chunk_size: int = Form(default=1000, ge=100, le=5000),
    chunk_overlap: int = Form(default=200, ge=0, le=1000),
):
    """
    Upload and ingest a document into the Qdrant vector store.

    Accepted formats: .pdf, .docx, .txt

    The document is:
    1. Saved temporarily
    2. Loaded and chunked
    3. Embedded via nomic-embed-text
    4. Upserted into Qdrant (idempotent — same document can be re-uploaded safely)

    Returns ingestion statistics including chunk count and timing.
    """
    # Validate file extension
    allowed = {".pdf", ".docx", ".txt"}
    suffix = os.path.splitext(file.filename or "")[1].lower()
    if suffix not in allowed:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type {suffix!r}. Accepted: {sorted(allowed)}"
        )

    # Save to a temp path in the data directory
    upload_dir = os.path.join(
        os.path.dirname(__file__), "..", "..", "data", "uploads"
    )
    os.makedirs(upload_dir, exist_ok=True)
    temp_path = os.path.join(upload_dir, file.filename)

    try:
        content = await file.read()
        with open(temp_path, "wb") as fh:
            fh.write(content)

        result: IngestionResult = ingest_document(
            file_path=temp_path,
            collection_name=collection,
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
            department=department if department else None,
        )
    except FileNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    except ConnectionError as exc:
        logger.error("Qdrant/Ollama not reachable: %s", exc)
        raise HTTPException(status_code=503, detail=f"AI services unavailable: {exc}")
    except Exception as exc:
        logger.exception("Unexpected error in ingest_document_endpoint")
        raise HTTPException(status_code=500, detail=f"Internal error: {exc}")

    return IngestResponse(
        filename=result.filename,
        document_id=result.document_id,
        doc_type=result.doc_type,
        total_chars=result.total_chars,
        chunks_created=result.chunks_created,
        chunks_upserted=result.chunks_upserted,
        elapsed_total_s=result.elapsed_total_s,
        collection=collection,
    )


@router.get("/api/rag/collection", response_model=CollectionInfoResponse, tags=["RAG"])
def collection_info_endpoint(collection: str = QDRANT_COLLECTION):
    """
    Return metadata about the specified Qdrant collection.

    Useful for monitoring how many document chunks are indexed.
    """
    try:
        client = get_client()
    except ConnectionError as exc:
        raise HTTPException(status_code=503, detail=f"Qdrant unavailable: {exc}")

    if not collection_exists(client, collection):
        raise HTTPException(
            status_code=404,
            detail=f"Collection {collection!r} does not exist. Ingest documents first."
        )

    try:
        info = get_collection_info(client, collection)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to get collection info: {exc}")

    return CollectionInfoResponse(
        name=info["name"],
        status=str(info["status"]),
        points_count=info["points_count"] or 0,
        vector_size=info["vector_size"],
        distance=str(info["distance"]),
    )
